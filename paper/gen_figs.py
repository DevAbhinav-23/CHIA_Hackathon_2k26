"""Generate fig-motivation.tex and fig-analysis.tex as plain TikZ.

Every plotted value is taken from main.tex (Tables I/II and the source comments
that cite the measurement files); derived values are simple ratios shown here.
"""
import math

F = r"\sffamily\fontsize{6}{7}\selectfont"
FS = r"\sffamily\fontsize{5.5}{6.3}\selectfont"
FT = r"\sffamily\bfseries\fontsize{6.6}{7.6}\selectfont"
HAIR = "line width=0.4pt, draw=black!55"
GRID = "line width=0.3pt, draw=black!12"


def n(x):
    return f"{x:.3f}"


def fmt_int(v):
    return f"{v:,}".replace(",", "{,}")


# --------------------------------------------------------------------------- axes
def yaxis(out, x0, x1, ticks, scale, lab_fn, label=None, label_dx=0.62):
    for t in ticks:
        y = t * scale
        out.append(rf"\draw[{GRID}] ({n(x0)},{n(y)}) -- ({n(x1)},{n(y)});")
        out.append(rf"\draw[{HAIR}] ({n(x0-0.06)},{n(y)}) -- ({n(x0)},{n(y)});")
        out.append(rf"\node[anchor=east, inner sep=1pt, font={FS}, color=black!70] at ({n(x0-0.07)},{n(y)}) {{{lab_fn(t)}}};")
    out.append(rf"\draw[{HAIR}] ({n(x0)},0) -- ({n(x0)},{n(ticks[-1]*scale)});")
    out.append(rf"\draw[{HAIR}] ({n(x0)},0) -- ({n(x1)},0);")
    if label:
        ym = ticks[-1] * scale / 2
        out.append(rf"\node[rotate=90, anchor=south, inner sep=0pt, font={FS}, color=black!70] at ({n(x0-label_dx)},{n(ym)}) {{{label}}};")


def bar(out, xc, w, h, style):
    if h <= 0:
        return
    out.append(rf"\fill[{style}] ({n(xc-w/2)},0) rectangle ({n(xc+w/2)},{n(h)});")


def vlabel(out, xc, h, text, color="black!80"):
    out.append(rf"\node[anchor=south, inner sep=0.8pt, font={FS}, color={color}] at ({n(xc)},{n(h)}) {{{text}}};")


def xlabel(out, xc, text, y=-0.07):
    out.append(rf"\node[anchor=north, align=center, inner sep=0pt, font={FS}] at ({n(xc)},{n(y)}) {{{text}}};")


def title(out, x, y, text):
    out.append(rf"\node[anchor=south west, inner sep=0pt, font={FT}] at ({n(x)},{n(y)}) {{{text}}};")


def key(out, x, y, style, text):
    out.append(rf"\fill[{style}] ({n(x)},{n(y-0.06)}) rectangle ({n(x+0.2)},{n(y+0.07)});")
    out.append(rf"\node[anchor=west, inner sep=0pt, font={FS}] at ({n(x+0.26)},{n(y)}) {{{text}}};")


SEED = "fill=agB!70, draw=agB, line width=0.4pt"
SEED1 = "fill=agF, draw=agB, line width=0.4pt"
SEED2 = "fill=agB!78, draw=agB, line width=0.4pt"
MUT = "fill=dsF, draw=dsB, line width=0.4pt"
APP = "fill=rbF, draw=rbB, line width=0.4pt"
APP2 = "fill=rbB!55, draw=rbB, line width=0.4pt"
BACK = "fill=black!55, draw=black!70, line width=0.4pt"


# ======================================================================= motivation
def motivation():
    o = [r"% fig-motivation.tex -- GENERATED by gen_figs.py; edit the generator.",
         r"% (a) 82 opened / 65 closed in 12 months; 101 open, median age 911 d",
         r"%     analysis/measurements/2026-09-13-frd-followups.md M1",
         r"% (b) about 127 of 187 seeds unreachable from FIRRTL; 171 of 187 exact SDK;",
         r"%     published image compiled -DNDEBUG (no handler); ours 536 of 555 objects",
         r"\begin{tikzpicture}[x=1cm,y=1cm]"]
    # ---- panel (a)
    H, S = 1.60, 1.60 / 120
    x0, x1 = 0.72, 3.20
    title(o, 0.0, 1.86, "(a) The queue does not drain")
    yaxis(o, x0, x1, [0, 50, 100], S, lambda t: str(t), label="bug-labelled issues", label_dx=0.42)
    xs = [1.03, 1.77, 2.78]
    vals = [82, 65, 101]
    styles = [APP2, APP, BACK]
    for xc, v, st in zip(xs, vals, styles):
        bar(o, xc, 0.44, v * S, st)
        vlabel(o, xc, v * S, str(v))
    # net inflow bracket between opened and closed
    yo, yc = 82 * S, 65 * S
    xb = 1.77 + 0.29
    o.append(rf"\draw[line width=0.4pt, draw=hgB] ({n(1.77-0.22)},{n(yo)}) -- ({n(xb)},{n(yo)});")
    o.append(rf"\draw[line width=0.5pt, draw=hgB, {{Latex[length=2.4pt,width=2.2pt]}}-{{Latex[length=2.4pt,width=2.2pt]}}] ({n(xb)},{n(yc)}) -- ({n(xb)},{n(yo)});")
    o.append(rf"\node[anchor=west, inner sep=1pt, font={FS}, color=hgB] at ({n(xb)},{n((yo+yc)/2)}) {{+17}};")
    xlabel(o, 1.03, r"opened")
    xlabel(o, 1.77, r"closed")
    o.append(rf"\draw[line width=0.3pt, draw=black!45] (0.80,-0.31) -- (2.00,-0.31);")
    o.append(rf"\node[anchor=north, inner sep=0pt, font={FS}, color=black!70] at (1.40,-0.35) {{in 12 months}};")
    xlabel(o, 2.78, r"open now\\911\,d median")
    # ---- panel (b)
    bx0, bw = 3.72, 4.62
    title(o, bx0 - 0.02, 1.86, "(b) What a naive loop cannot see")
    rows = [
        ("Seeds a FIRRTL input can reach", 60 / 187, r"$\approx$60", r"$\approx$127 need \texttt{circt-opt} or SV"),
        ("Seeds with an exactly matching prebuilt SDK", 171 / 187, "171 of 187", "16"),
        ("Objects asserting, CHIA's published image", 0.0, "", r"none: built with \texttt{-DNDEBUG}"),
        ("Objects asserting, this loop's image", 536 / 555, "536 of 555", "19"),
    ]
    ys = [1.47, 1.02, 0.57, 0.12]
    bh = 0.16
    for (lab, frac, lin, lout), y in zip(rows, ys):
        o.append(rf"\node[anchor=south west, inner sep=0pt, font={FS}, color=black!85] at ({n(bx0)},{n(y+bh/2+0.025)}) {{{lab}}};")
        xm = bx0 + bw * frac
        if frac > 0:
            o.append(rf"\fill[{APP}] ({n(bx0)},{n(y-bh/2)}) rectangle ({n(xm)},{n(y+bh/2)});")
        o.append(rf"\fill[{MUT}] ({n(xm)},{n(y-bh/2)}) rectangle ({n(bx0+bw)},{n(y+bh/2)});")
        if lin:
            o.append(rf"\node[anchor=east, inner sep=1.5pt, font={FS}, color=rbB!60!black] at ({n(xm)},{n(y)}) {{{lin}}};")
        if frac < 0.5:
            o.append(rf"\node[anchor=west, inner sep=1.5pt, font={FS}, color=black!60] at ({n(xm)},{n(y)}) {{{lout}}};")
        else:
            o.append(rf"\node[anchor=west, inner sep=1.5pt, font={FS}, color=black!60] at ({n(bx0+bw)},{n(y)}) {{{lout}}};")
    o.append(r"\end{tikzpicture}")
    return "\n".join(o) + "\n"


# ======================================================================= analysis
def analysis():
    o = [r"% fig-analysis.tex -- GENERATED by gen_figs.py; edit the generator.",
         r"% Values: Table II of main.tex and ratios of its cells; (d) from W-04b 1,2,4.",
         r"%  (a) seeded 134+624=758 inputs, 15+69=84 cand., 3+14=17 fp, 3+12=15 gated;",
         r"%      mutation 2 x 1,154 = 2,308 inputs and 0 everywhere else",
         r"%  (b) 15/134=11.2, 69/624=11.1, 3/134=2.2, 12/624=1.9 per 100 inputs",
         r"%  (c) 44.49/9=4.9, 122.77/43=2.9 per seed; 44.49/3=14.8, 122.77/12=10.2 per bug",
         r"%  (d) +18.4% wall, +24.5% bytes, +4.8% median per probe",
         r"\begin{tikzpicture}[x=1cm,y=1cm]"]
    H = 1.75
    TY = 2.05
    # ---- (a) log funnel
    x0, x1 = 0.78, 5.30
    S = H / 4  # decades
    title(o, 0.0, TY, "(a) Attrition through the gates, both campaigns")
    yaxis(o, x0, x1, [0, 1, 2, 3, 4], S,
          lambda t: {0: "1", 1: "10", 2: "100", 3: "1k", 4: "10k"}[t], label="count (log scale)", label_dx=0.45)
    cats = [("inputs\\\\written", 758, 2308), ("candidates", 84, 0),
            ("new finger-\\\\prints", 17, 0), ("through\\\\the gate", 15, 0)]
    gx = [1.40, 2.45, 3.50, 4.55]
    bw = 0.36
    for (lab, s, m), xc in zip(cats, gx):
        xs, xm = xc - bw / 2 - 0.02, xc + bw / 2 + 0.02
        hs = S * math.log10(s)
        bar(o, xs, bw, hs, SEED)
        vlabel(o, xs, hs, fmt_int(s))
        if m > 0:
            hm = S * math.log10(m)
            bar(o, xm, bw, hm, MUT)
            vlabel(o, xm, hm, fmt_int(m))
        else:
            vlabel(o, xm, 0.0, "0", color="dsB!70!black")
        xlabel(o, xc, lab)
    key(o, 2.95, 1.70, SEED, "seeded: reads the fix")
    key(o, 2.95, 1.46, MUT, "mutation: same seed tests")
    # ---- (b) yield per 100 inputs
    x0, x1 = 6.30, 9.55
    S = H / 14
    title(o, 5.78, TY, "(b) Yield per 100 inputs")
    yaxis(o, x0, x1, [0, 5, 10], S, lambda t: str(t), label="per 100 inputs", label_dx=0.36)
    groups = [("candidates", [11.2, 11.1, 0.0]), ("through the gate", [2.2, 1.9, 0.0])]
    gx = [7.05, 8.60]
    st = [SEED1, SEED2, MUT]
    bw = 0.28
    for (lab, vals), xc in zip(groups, gx):
        for i, v in enumerate(vals):
            xb = xc + (i - 1) * (bw + 0.16)
            bar(o, xb, bw, v * S, st[i])
            vlabel(o, xb, v * S, f"{v:.1f}" if v > 0 else "0",
                   color="black!80" if v > 0 else "dsB!70!black")
        xlabel(o, xc, lab)
    key(o, 8.35, 1.70, SEED1, "seeded 1")
    key(o, 8.35, 1.46, SEED2, "seeded 2")
    key(o, 8.35, 1.22, MUT, "mutation")
    # ---- (c) money
    x0, x1 = 10.60, 13.75
    S = H / 18
    title(o, 10.08, TY, "(c) List-price cost, USD")
    yaxis(o, x0, x1, [0, 5, 10, 15], S, lambda t: str(t), label="USD at list price", label_dx=0.36)
    groups = [("per seed probed", [4.9, 2.9]), ("per gated bug", [14.8, 10.2])]
    gx = [11.35, 12.95]
    bw = 0.38
    for (lab, vals), xc in zip(groups, gx):
        for i, v in enumerate(vals):
            xb = xc + (i - 0.5) * (bw + 0.05)
            bar(o, xb, bw, v * S, [SEED1, SEED2][i])
            vlabel(o, xb, v * S, f"{v:.1f}")
        xlabel(o, xc, lab)
    key(o, 10.80, 1.70, SEED1, "campaign 1")
    key(o, 10.80, 1.46, SEED2, "campaign 2")
    # ---- (d) price of assertions
    x0, x1 = 14.95, 18.05
    S = H / 30
    title(o, 14.43, TY, r"(d) Price of restoring assertions")
    yaxis(o, x0, x1, [0, 10, 20, 30], S, lambda t: f"+{t}\\%", label=None)
    vals = [("wall\\\\clock", 18.4), ("binary\\\\size", 24.5), ("median\\\\per probe", 4.8)]
    gx = [15.55, 16.50, 17.45]
    for (lab, v), xc in zip(vals, gx):
        bar(o, xc, 0.48, v * S, APP)
        vlabel(o, xc, v * S, f"+{v:.1f}\\%")
        xlabel(o, xc, lab)
    o.append(r"\end{tikzpicture}")
    return "\n".join(o) + "\n"


open("fig-motivation.tex", "w").write(motivation())
open("fig-analysis.tex", "w").write(analysis())
print("ok")
